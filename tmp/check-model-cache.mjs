import assert from 'node:assert/strict';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { loadModel, loadTexture, preloadLevel2Models, LEVEL2_MODEL_URLS, LEVEL2_TEXTURE_URLS } from '../src/systems/modelCache.js';
const originalLoad = GLTFLoader.prototype.loadAsync;
const originalTextureLoad = THREE.TextureLoader.prototype.loadAsync;
const master = new THREE.Group();
const texture = new THREE.Texture({ width: 1, height: 1 });
master.add(new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshStandardMaterial({ map: texture })));
const gltf = { scene: master, parser: { async getDependency() { return texture; } } };
const counts = new Map();
let active = 0;
let peak = 0;
GLTFLoader.prototype.loadAsync = async url => {
  counts.set(url, (counts.get(url) ?? 0) + 1);
  active++;
  peak = Math.max(peak, active);
  await new Promise(resolve => queueMicrotask(resolve));
  active--;
  if (url === 'retry-test' && counts.get(url) === 1) throw Error('Temporary network error');
  return gltf;
};
THREE.TextureLoader.prototype.loadAsync = async url => {
  counts.set(url, (counts.get(url) ?? 0) + 1);
  return texture;
};
const [first, second] = await Promise.all([loadModel('shared-test'), loadModel('shared-test')]);
assert.equal(counts.get('shared-test'), 1, 'Concurrent loads share one request/decode');
assert.notEqual(first.scene, second.scene);
assert.notEqual(first.scene.children[0].geometry, second.scene.children[0].geometry);
assert.notEqual(first.scene.children[0].material, second.scene.children[0].material);
assert.notEqual(first.scene.children[0].material.map, second.scene.children[0].material.map);
assert.equal(first.scene.children[0].material.map.image, texture.image, 'Decoded image is reused');
first.scene.children[0].material.color.setHex(0x00ff00);
first.scene.children[0].geometry.dispose();
first.scene.children[0].material.dispose();
first.scene.children[0].material.map.dispose();
const third = await loadModel('shared-test');
assert.equal(third.scene.children[0].material.color.getHex(), 0xffffff, 'Prior level state/disposal cannot contaminate a reload');
assert.equal(counts.get('shared-test'), 1);
assert.notEqual(await third.parser.getDependency('texture', 0), texture, 'Extra material maps also have independent ownership');
await assert.rejects(loadModel('retry-test'));
await loadModel('retry-test');
assert.equal(counts.get('retry-test'), 2, 'Failed requests can retry');
peak = 0;
const progress = [];
const [errors] = await Promise.all([preloadLevel2Models((done, total) => progress.push([done, total])), preloadLevel2Models()]);
assert.equal(errors.length, 0);
assert.ok(peak <= 2, 'Background work is limited to two assets at a time');
assert.equal(progress.length, LEVEL2_MODEL_URLS.length + LEVEL2_TEXTURE_URLS.length);
assert.deepEqual(progress.at(-1), [11, 11]);
assert.ok(LEVEL2_MODEL_URLS.every(url => counts.get(url) === 1));
await preloadLevel2Models();
assert.ok(LEVEL2_MODEL_URLS.every(url => counts.get(url) === 1), 'Repeated entries do not re-download');
assert.ok(LEVEL2_TEXTURE_URLS.every(url => counts.get(url) === 1), 'Button textures preload once');
const buttonTexture = loadTexture(LEVEL2_TEXTURE_URLS[0]);
assert.notEqual(buttonTexture, texture);
assert.equal(buttonTexture.image, texture.image, 'Button construction uses decoded image immediately');
GLTFLoader.prototype.loadAsync = originalLoad;
THREE.TextureLoader.prototype.loadAsync = originalTextureLoad;
console.log('Model cache checks passed: request deduplication, decoded-image reuse, independent disposal/state, retries, bounded preloading and progress.');
