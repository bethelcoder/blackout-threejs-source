import assert from 'node:assert/strict';
import * as THREE from 'three';
import { buildSecurityCamera, createRoomSecurityView, createSecuritySweep } from '../src/scenes/securityCamera.js';
globalThis.document = { createElementNS: () => ({ addEventListener() {}, removeEventListener() {}, set src(value) {} }) };
const view = createRoomSecurityView();
assert.ok(view.position.y > 5.8, 'Camera mounted near ceiling');
const blockers = [];
const sweep = createSecuritySweep(view, new THREE.Group(), blockers);
const center = new THREE.Vector3(0, 1.7, -1);
assert.ok(sweep.sees(center), 'Center detected when camera faces forward');
blockers.push(new THREE.Box3(new THREE.Vector3(-1, 0, -6), new THREE.Vector3(1, 6, -5)));
assert.ok(!sweep.sees(center), 'Cover blocks detection');
blockers.length = 0;
sweep.update(7);
assert.ok(!sweep.sees(center), 'Sweep creates a safe interval at the center');
const right = new THREE.Vector3(6, 1.7, -4.8);
assert.ok(sweep.sees(right), 'Camera detects the right side while facing right');
sweep.update(14);
assert.ok(!sweep.sees(right), 'Right side becomes safe as camera sweeps left');
assert.ok(sweep.sees(new THREE.Vector3(-6, 1.7, -4.8)), 'Left side detected on return sweep');
sweep.update(7);
assert.ok(sweep.sees(center), 'Camera returns to original direction after a full cycle');
const cone = sweep.group.children[0];
const vertex = new THREE.Vector3();
for (let i = 1; i < cone.geometry.attributes.position.count; i += 3) {
  vertex.fromBufferAttribute(cone.geometry.attributes.position, i);
  assert.ok(vertex.y >= 0, 'Visible cone is clipped at the floor');
}
assert.ok(view.fov < 50, 'Camera no longer watches the entire room at once');
sweep.dispose();
const model = buildSecurityCamera();
assert.equal(model.group.children.length, 12, 'All supplied camera components retained');
assert.ok(model.group.children.every(mesh => mesh.material.map && mesh.material.normalMap && mesh.geometry.attributes.uv));
model.group.position.copy(view.position);
model.group.lookAt(0, 0, -0.8);
model.group.updateMatrixWorld(true);
const bounds = new THREE.Box3().setFromObject(model.group);
assert.ok(bounds.max.y < 6.66, 'Model fits below ceiling tiles');
assert.ok(bounds.min.z > -10, 'Model fits inside the back wall');
const facing = model.group.getWorldDirection(new THREE.Vector3());
assert.ok(facing.z > 0 && facing.y < 0, 'Lens faces down into room');
model.dispose();
console.log('Camera checks passed: imported model, clearance, slow sweep, safe intervals, cover occlusion, visible cone floor clipping.');
