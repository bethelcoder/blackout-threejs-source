import assert from 'node:assert/strict';
import { RenderQuality } from '../src/systems/renderQuality.js';
const renderer = { calls: 0, setPixelRatio(r) { this.ratio = r; this.calls++; }, setSize(w,h) { this.w=w; this.h=h; } };
const quality = new RenderQuality(renderer);
quality.resize(1920,1080,2);
assert.ok(renderer.ratio ** 2 * 1920 * 1080 <= 2400001);
const initial=renderer.ratio;
for(let i=0;i<400;i++) quality.update(1/30);
assert.ok(renderer.ratio < initial);
assert.ok(quality.scale >= 0.65);
const low=quality.scale;
for(let i=0;i<800;i++) quality.update(1/60);
assert.ok(quality.scale > low && quality.scale <= 1);
const before=quality.scale;
for(let i=0;i<30;i++) quality.update(2);
assert.equal(quality.scale,before);
quality.resize(800,600,1);
assert.ok(renderer.ratio <= 1);
const calls=renderer.calls;
for(let i=0;i<400;i++) quality.update(1/50);
assert.equal(renderer.calls,calls,'No buffer reallocations at stable frame rates');
console.log('Render quality checks passed: pixel budget, slow/fast recovery, stall rejection, resize and stable allocation.');
