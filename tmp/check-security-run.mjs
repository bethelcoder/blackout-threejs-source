import assert from 'node:assert/strict';
import { SecurityRun } from '../src/systems/securityRun.js';
const strikes = [], losses = [];
const run = new SecurityRun({ onStrike: source => strikes.push(source), onLose: source => losses.push(source) });
for (let i = 0; i < 59; i++) run.cameraExposure(0.05, true);
assert.equal(run.strikes, 0, 'No strike before three continuous seconds');
run.cameraExposure(0.05, false);
assert.equal(run.exposure, 0, 'Breaking sight resets exposure');
for (let i = 0; i < 60; i++) run.cameraExposure(0.05, true);
assert.equal(run.strikes, 1, 'Strike at exactly three seconds');
assert.deepEqual(strikes, ['camera']);
assert.equal(run.strike('laser'), false, 'Protection prevents repeated strikes');
run.cameraExposure(2, true);
assert.equal(run.exposure, 0, 'Protected exposure does not accumulate');
run.update(3);
assert.equal(run.strike('laser'), true);
assert.equal(run.strikes, 2);
run.update(3);
for (let i = 0; i < 60; i++) run.cameraExposure(0.05, true);
assert.equal(run.lost, true);
assert.deepEqual(losses, ['camera']);
assert.deepEqual(strikes, ['camera', 'laser'], 'Third strike ends attempt instead of respawning');
run.update(10);
run.strike('laser');
run.cameraExposure(10, true);
assert.equal(run.strikes, 3, 'Loss is final until retry');
assert.equal(losses.length, 1, 'Loss fires once');
run.reset();
assert.equal(run.strikes, 0);
assert.equal(run.exposure, 0);
assert.equal(run.lost, false);
assert.equal(run.grace, 0);
console.log('Security checks passed: continuous three-second exposure, cover reset, protection, three strikes, loss once, retry reset.');
