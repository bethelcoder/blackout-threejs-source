import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
const source = fs.readFileSync('src/main.js', 'utf8');
const start = source.indexOf('    // The spring arm and its collider tests');
const end = source.indexOf('\n  // Ensure first-person camera', start);
const block = source.slice(start, end).replace(/\n  }\s*$/, '');
const run = new Function('THREE','playerControls','camera','currentLevel','thirdPersonCamera','previousCameraMode','playerModel','LEVEL_BOUNDS','currentLevelIndex','MIN_CAMERA_PITCH','MAX_CAMERA_PITCH', block);
const camera = new THREE.PerspectiveCamera(); camera.position.set(0,1.7,0); camera.updateMatrixWorld(true);
const third = new THREE.PerspectiveCamera();
let reads = 0;
const level = { get colliders() { reads++; return [new THREE.Box3(new THREE.Vector3(-2,0,0.8),new THREE.Vector3(2,3,1))]; } };
const bounds = [{ minX:-7,maxX:7,minY:0.1,maxY:5,maxZ:7,minZ:-7 }];
run(THREE,{cameraMode:'first'},camera,level,third,'first',null,bounds,0,-1,1);
assert.equal(reads,0,'First-person mode skips third-person collider tests');
run(THREE,{cameraMode:'third'},camera,level,third,'first',null,bounds,0,-1,1);
assert.ok(reads>0,'Third-person mode still tests obstacles');
assert.ok(third.position.z>0 && third.position.z<0.8,'Third-person camera stops before obstruction');
assert.ok(third.position.toArray().every(Number.isFinite));
console.log('Camera performance checks passed: no spring-arm collision work in first person; third-person obstacle avoidance retained.');
