import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { arrangeVenatorSmallDoor, buildVenatorSmallDoor } from '../src/scenes/venatorSmallDoor.js';
import { arrangeVenatorRoom } from '../src/scenes/venatorRoom.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
async function parse(name) {
  const file = fs.readFileSync(`src/assets/models/${name}.glb`);
  return new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), '');
}
const [gltf, shell] = await Promise.all([parse('venator-small-door'), parse('venator-room-modules')]);
const door = arrangeVenatorSmallDoor(gltf.scene.clone(true));
const bounds = new THREE.Box3().setFromObject(door.group);
assert.ok(Math.abs(bounds.min.y) < 0.00001 && Math.abs(bounds.max.y - 3.2) < 0.00001, 'Door frame sits on floor at room scale');
assert.ok(bounds.min.x < -1.4 && bounds.max.x > 1.4 && bounds.min.z > -8, 'Door fits existing exit wall');
assert.ok(door.leaf.material.map && door.leaf.material.normalMap && door.leaf.material.emissiveMap, 'Original door material retained');
const aim = new THREE.Raycaster(new THREE.Vector3(0, 1.5, -7), new THREE.Vector3(0, 0, -1), 0, 2);
assert.ok(aim.intersectObject(door.leaf, true).length > 0, 'Closed door panel faces room');
assert.ok(door.frameColliders.every(box => !box.containsPoint(new THREE.Vector3(0, 1.5, -7.8))), 'Frame leaves walkable aperture');
const room = arrangeVenatorRoom(shell.scene);
room.updateMatrixWorld(true);
assert.equal(aim.intersectObject(room, true).length, 0, 'Imported wall panels leave real doorway');
const originalLoad = GLTFLoader.prototype.loadAsync;
GLTFLoader.prototype.loadAsync = async () => ({ scene: gltf.scene.clone(true) });
const scene = new THREE.Scene();
const colliders = [];
const loaded = buildVenatorSmallDoor({ scene, colliders });
await loaded.ready;
const leaf = scene.getObjectByName('Venator_Door1');
loaded.update(1, false);
assert.equal(leaf.position.y, 0, 'Locked door stays closed');
loaded.update(1, true);
assert.ok(leaf.position.y > 200, 'Unlocked door slides up');
assert.equal(colliders.length, 3);
loaded.dispose();
assert.equal(scene.children.length, 0);
assert.equal(colliders.length, 0);
const earlyOpen = buildVenatorSmallDoor({ scene });
earlyOpen.update(1, true);
await earlyOpen.ready;
assert.ok(scene.getObjectByName('Venator_Door1').position.y > 200, 'Unlock before model load is remembered');
earlyOpen.dispose();
const cancelled = buildVenatorSmallDoor({ scene });
cancelled.dispose();
await cancelled.ready;
assert.equal(scene.children.length, 0);
GLTFLoader.prototype.loadAsync = originalLoad;
console.log('Small-door checks passed: original frame/panel/textures, scale, orientation, wall aperture, locked/open animation, collision, cleanup and late loads.');
