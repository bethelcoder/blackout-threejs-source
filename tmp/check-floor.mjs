import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { tileFloorModules } from '../src/scenes/modularFloor.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const file = fs.readFileSync('src/assets/models/modular-sci-fi-floor.glb');
const buffer = file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength);
const gltf = await new GLTFLoader().parseAsync(buffer, '');
const floor = tileFloorModules(gltf.scene);
assert.equal(floor.children.length, 4, 'Four original module designs');
assert.equal(floor.children.reduce((count, mesh) => count + mesh.count, 0), 56, '56 panels cover room');
const bounds = new THREE.Box3().setFromObject(floor);
assert.ok(Math.abs(bounds.min.x + 7) < 0.001 && Math.abs(bounds.max.x - 7) < 0.001);
assert.ok(Math.abs(bounds.min.z + 8) < 0.001 && Math.abs(bounds.max.z - 8) < 0.001);
assert.ok(Math.abs(bounds.max.y) < 0.00001, 'Walking surface stays at zero');
assert.ok(floor.children.every(mesh => mesh.material.map && mesh.material.normalMap && mesh.material.metalnessMap && mesh.material.emissiveMap), 'Original material maps retained');
console.log('Floor checks passed: valid GLB, four textured variants, 56 instanced panels, exact room coverage and walking height.');
