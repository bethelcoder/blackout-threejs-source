import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { preloadLevel2Models } from '../src/systems/modelCache.js';
import { buildLevel2 } from '../src/scenes/level2.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const ctx = new Proxy({}, { get: (_, key) => key === 'measureText' ? text => ({ width: text.length * 8 }) : key.startsWith('create') ? () => ({ addColorStop() {} }) : () => {} });
globalThis.document = { createElement: () => ({ getContext: () => ctx }) };
const originalModelLoad = GLTFLoader.prototype.loadAsync;
const originalTextureLoad = THREE.TextureLoader.prototype.loadAsync;
let modelRequests = 0;
let textureRequests = 0;
GLTFLoader.prototype.loadAsync = async url => {
  modelRequests++;
  const file = fs.readFileSync(fileURLToPath(url));
  return new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), '');
};
THREE.TextureLoader.prototype.loadAsync = async () => { textureRequests++; return new THREE.Texture({ width: 1, height: 1 }); };
assert.deepEqual(await preloadLevel2Models(), []);
assert.equal(modelRequests, 7);
assert.equal(textureRequests, 4);
const scene = new THREE.Scene();
const args = { scene, aiState: { raise() {}, decay() {} }, hud: { setObjective() {}, markLevelComplete() {} }, terminalUI: { open: false, show() {} } };
const names = ['Venator walls and ceiling', 'Imported terminal workstation', 'Office chair in front of terminal desk', 'Data Center Server Rack', 'Server Racking System', 'Venator small door in front of desk'];
let level = buildLevel2(args);
await level.ready;
for (const name of names) assert.ok(scene.getObjectByName(name), `Ready includes ${name}`);
assert.equal(scene.children.filter(object => object.name.startsWith('Data Center Server Rack') || object.name.startsWith('Server Racking System')).length, 10);
assert.equal(modelRequests, 7, 'Scene construction reuses preloaded models');
assert.equal(textureRequests, 4, 'Button reuses preloaded images');
scene.getObjectByName('Laser shutdown button').userData.onInteract();
assert.equal(scene.getObjectByName('Imported Venator overhead light strips').material.emissive.getHex(), 0xffffff);
args.terminalUI.onSolved();
level.update(1, new THREE.PerspectiveCamera());
assert.ok(scene.getObjectByName('Venator_Door1').position.y > 200);
level.dispose();
scene.clear();
level = buildLevel2(args);
await level.ready;
for (const name of names) assert.ok(scene.getObjectByName(name));
assert.equal(scene.getObjectByName('Imported Venator overhead light strips').material.emissive.getHex(), 0x33ff66, 'Fresh level restores green laser-active lighting');
assert.equal(scene.getObjectByName('Venator_Door1').position.y, 0, 'Fresh level restores closed door');
assert.equal(modelRequests, 7, 'Re-entry does not download or parse models again');
assert.equal(textureRequests, 4);
level.dispose();
GLTFLoader.prototype.loadAsync = originalModelLoad;
THREE.TextureLoader.prototype.loadAsync = originalTextureLoad;
console.log('Full Level 2 readiness checks passed: all models present at ready, seven cached model loads, four preloaded button textures, no repeated requests, clean gameplay state on re-entry.');
