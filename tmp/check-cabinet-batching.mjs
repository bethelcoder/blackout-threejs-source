import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { batchCabinet } from '../src/scenes/coreRoomProps.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const bytes = fs.readFileSync('public/models/metal-storage-cabinet.glb');
const { scene } = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
const before = new THREE.Box3().setFromObject(scene);
let triangles = 0, meshes = 0;
const materials = new Set();
scene.traverse(object => { if (!object.isMesh) return; meshes++; materials.add(object.material); triangles += (object.geometry.index?.count ?? object.geometry.attributes.position.count) / 3; });
const batched = batchCabinet(scene);
const after = new THREE.Box3().setFromObject(batched);
assert.equal(meshes, 189);
assert.equal(batched.children.length, 5);
assert.ok(before.min.distanceTo(after.min) < 1e-5 && before.max.distanceTo(after.max) < 1e-5, 'Exact shape bounds retained');
assert.equal(batched.children.reduce((sum, mesh) => sum + mesh.geometry.attributes.position.count / 3, 0), triangles, 'All triangles retained');
assert.ok(batched.children.every(mesh => materials.has(mesh.material)), 'Original materials retained');
console.log(`Cabinet batching passed: ${meshes} -> ${batched.children.length} meshes, same triangles, materials and bounds.`);
