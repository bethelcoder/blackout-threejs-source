import assert from 'node:assert/strict';
import * as THREE from 'three';
import { InteractionTarget } from '../src/systems/interactionTarget.js';

const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera(70, 16 / 9, 0.1, 100);
scene.add(camera);
const targeting = new InteractionTarget();
const accepts = object => object.userData.interactable;
const item = new THREE.Mesh(new THREE.BoxGeometry(0.12, 0.12, 0.12), new THREE.MeshBasicMaterial());
item.userData.interactable = true;
item.position.set(0.14, 0, -2);
scene.add(item);
const find = () => { scene.updateMatrixWorld(true); return targeting.find(camera, scene, 3.2, accepts); };
assert.equal(find(), item, 'Small off-centre object is selected');
const hand = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 0.1), item.material);
hand.position.z = -0.3;
camera.add(hand);
assert.equal(find(), item, 'First person hands do not obstruct selection');
const wall = new THREE.Mesh(new THREE.BoxGeometry(2, 2, 0.1), item.material);
wall.position.z = -1;
scene.add(wall);
assert.equal(find(), null, 'Walls prevent assisted selection');
wall.visible = false;
assert.equal(find(), item, 'Invisible geometry does not block selection');
item.position.z = -5;
assert.equal(find(), null, 'Assistance respects reach');
item.position.set(1.3, 0, -2);
assert.equal(find(), null, 'Objects far from aim are not selected');
item.position.set(0, 0, -2);
assert.equal(find(), item, 'Direct aiming still selects');
item.userData.reach = 1;
assert.equal(find(), null, 'Object-specific reach is respected');
item.userData.reach = 3.2;
let distantRaycasts = 0;
const distant = new THREE.Mesh(item.geometry, item.material);
distant.position.set(0, 0, -50);
distant.raycast = () => { distantRaycasts++; };
scene.add(distant);
assert.equal(find(), item);
assert.equal(distantRaycasts, 0, 'Distant meshes never receive expensive raycasts');
let blockerRaycasts = 0;
wall.visible = true;
wall.raycast = () => { blockerRaycasts++; };
item.position.set(1.3, 0, -2);
assert.equal(find(), null);
assert.equal(blockerRaycasts, 0, 'No full-scene occlusion raycast without an aimed candidate');
wall.visible = false;
item.position.set(0, 0, -2);
let candidateRaycasts = 0;
const raycast = item.raycast;
item.raycast = function (...args) { candidateRaycasts++; return raycast.apply(this, args); };
assert.equal(find(), item);
assert.equal(candidateRaycasts, 1, 'An aimed item is not raycast again for occlusion');
const narrow = new THREE.Mesh(new THREE.BoxGeometry(0.1, 20, 0.1, 1, 100, 1), item.material);
narrow.position.set(1, 0, -1);
let triangleReads = 0;
const getIndex = narrow.geometry.index.getX;
narrow.geometry.index.getX = function (index) { triangleReads++; return getIndex.call(this, index); };
scene.add(narrow);
assert.equal(find(), item, 'Off-axis narrow scenery does not obstruct the item');
assert.equal(triangleReads, 0, 'A tight box rejects tall geometry before testing triangles');
console.log('Interaction targeting checks passed.');
