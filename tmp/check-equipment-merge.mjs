import assert from 'node:assert/strict';
import * as THREE from 'three';
import { EquipmentSystem } from '../src/systems/equipment.js';
import { BackpackUI } from '../src/systems/backpackUI.js';
import { buildHeldTool } from '../src/systems/heldTools.js';
import { sound } from '../src/systems/audio.js';

sound.playSwitch = sound.playKeypadBeep = () => {};
globalThis.document = { getElementById: () => null };
const light = new THREE.SpotLight();
const equipment = new EquipmentSystem(new THREE.Camera(), light);
let viewTool, notifications = 0;
equipment.setViewmodel({ setTool(id) { viewTool = id; } });
equipment.onEquipChange(() => notifications++);
equipment.equipTool('uv_flashlight');
assert.equal(viewTool, 'uv_flashlight');
assert.equal(light.intensity, 12);
assert.equal(light.color.getHex(), 0xc38aff);
assert.equal(equipment.toggleTorch(), false);
assert.equal(equipment.equippedTool, 'uv_flashlight');
assert.equal(light.intensity, 0);
assert.equal(equipment.toggleTorch(), true);
const bag = Object.assign(Object.create(BackpackUI.prototype), { equipment, render() {} });
bag._handleItemClick({ id: 'uv_flashlight', name: 'UV Flashlight', type: 'tool' });
assert.equal(equipment.torchOn, false);
bag._handleItemClick({ id: 'torch', name: 'Inspection Torch', type: 'tool' });
assert.equal(equipment.equippedTool, 'torch');
assert.equal(light.intensity, 3.5);
equipment.equipTool('wrench');
assert.equal(light.intensity, 3.5, 'Holding tools keeps the headlamp on');
equipment.unequipTool();
assert.equal(viewTool, null);
assert.equal(light.intensity, 3.5);
bag._handleItemClick({ id: 'technical_guide', name: 'Logbook', type: 'document' });
assert.equal(equipment.equippedTool, 'technical_guide');
bag._handleItemClick({ id: 'technical_guide', name: 'Logbook', type: 'document' });
assert.equal(equipment.equippedTool, null);
assert.ok(notifications >= 9);
assert.ok(buildHeldTool('uv_flashlight')?.isGroup, 'UV torch exists in both hand views');
console.log('Merged equipment checks passed: UV beam, toggling, bag clicks, held documents, notifications and headlamp.');
