import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { arrangeVentCover } from '../src/scenes/ventCover.js';
import { buildMaintenanceVent } from '../src/scenes/maintenanceVent.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const context = new Proxy({}, { get: (_, key) => key.startsWith('create') ? () => ({ addColorStop() {} }) : () => {} });
const inventory = { textContent: '', classList: { add() {}, remove() {} } };
globalThis.document = { createElement: () => ({ getContext: () => context }), getElementById: () => inventory };
const file = fs.readFileSync('src/assets/models/maintenance-vent-cover.glb');
const gltf = await new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), '');
const cover = arrangeVentCover(gltf.scene.clone(true));
cover.updateMatrixWorld(true);
const bounds = new THREE.Box3().setFromObject(cover);
assert.ok(Math.abs(bounds.getSize(new THREE.Vector3()).y - 1.3) < 0.00001, 'Cover fits original opening');
assert.ok(Math.abs(bounds.getCenter(new THREE.Vector3()).x - 0.65) < 0.00001, 'Cover aligns with existing hinge');
assert.ok(bounds.min.z >= 0.0149 && bounds.max.z < 0.06, 'Cover fits behind existing retaining screws');
const originalLoad = GLTFLoader.prototype.loadAsync;
GLTFLoader.prototype.loadAsync = async () => gltf;
const route = buildMaintenanceVent({ aiState: { raise() {} }, hud: { setObjective() {} } });
await route.ready;
const imported = route.group.getObjectByName('Imported Vent.usdz door');
assert.ok(imported);
assert.equal(route.group.getObjectByName('Grille slat').visible, false, 'Old louvers replaced');
assert.equal(route.group.getObjectByName('Grille backing').visible, true, 'Dark backing retained');
const hinge = route.group.getObjectByName('Grille hinge');
assert.equal(imported.parent.parent, hinge, 'Original hinge carries new model');
const toolbox = route.group.getObjectByName('Under-stair toolbox');
const vent = route.group.getObjectByName('Vent assembly');
toolbox.userData.onInteract();
for (let i = 0; i < 30; i++) route.update(1 / 60);
const screwdriver = route.group.getObjectByName('Screwdriver');
assert.ok(screwdriver.visible);
screwdriver.userData.onInteract();
vent.userData.onHold(4);
for (let i = 0; i < 30; i++) route.update(1 / 60);
assert.ok(hinge.rotation.y < -1.2, 'Screwdriver still opens imported vent');
assert.ok(imported.visible);
const screws = [];
route.group.traverse(object => { if (object.name === 'Retaining screw') screws.push(object); });
assert.equal(screws.length, 4);
assert.ok(screws.every(screw => !screw.visible));
assert.match(vent.userData.getLabel(), /Read the rolled paper inside/);
route.dispose();
const cancelled = buildMaintenanceVent({ aiState: { raise() {} }, hud: { setObjective() {} } });
cancelled.dispose();
await cancelled.ready;
assert.equal(cancelled.group.getObjectByName('Imported Vent.usdz door'), undefined);
GLTFLoader.prototype.loadAsync = originalLoad;
console.log('Vent checks passed: original model/textures, hinge fit, replaced louvers, screwdriver/toolbox puzzle, opening, screws and cancelled loading.');
