import assert from 'node:assert/strict';
import * as THREE from 'three';
import { PlayerControls } from '../src/systems/playerControls.js';
globalThis.document = { addEventListener() {}, removeEventListener() {} };
const camera = new THREE.PerspectiveCamera();
const player = new PlayerControls(camera, { ownerDocument: document });
player.controls.isLocked = true;
assert.equal(player.cameraMode, 'first');
player._onKey({ code: 'KeyV', repeat: false }, true);
assert.equal(player.cameraMode, 'third', 'V preserves incoming third-person mode');
player._onKey({ code: 'KeyV', repeat: true }, true);
player._onKey({ code: 'KeyV', repeat: false }, false);
assert.equal(player.cameraMode, 'third', 'Holding/releasing V does not toggle repeatedly');
player._onKey({ code: 'KeyV', repeat: false }, true);
assert.equal(player.cameraMode, 'first');
const key = (code, down) => player._onKey({ code, repeat: false, preventDefault() {} }, down);
key('KeyC', true);
player.update(1 / 60);
assert.equal(player.height, 0.95);
assert.equal(camera.position.y, 0.95, 'Crouch keeps feet on floor');
assert.equal(camera.userData.playerHeight, 0.95, 'Laser sensor receives crouched height');
key('Space', true);
player.update(1 / 60);
assert.equal(camera.position.y, 0.95, 'Cannot jump while crouched');
player.colliders = [new THREE.Box3(new THREE.Vector3(-1, 1.2, -1), new THREE.Vector3(1, 1.4, 1))];
key('KeyC', false);
player.update(1 / 60);
assert.equal(player.height, 0.95, 'Low ceiling blocks standing');
player.colliders = [];
player.update(1 / 60);
assert.equal(camera.position.y, 1.7, 'Stand when headroom clears');
key('ControlLeft', true);
player.update(1 / 60);
assert.equal(player.height, 0.95, 'Ctrl also ducks');
player.teleport(new THREE.Vector3(0, 1.7, 6));
assert.equal(player.height, 1.7, 'Alarm teleport restores standing body');
assert.equal(player.move.crouch, false);
key('Space', true);
let peak = 0;
for (let frame = 0; frame < 45; frame++) {
  player.update(1 / 60);
  peak = Math.max(peak, camera.position.y - player.height);
}
assert.ok(peak > 0.8, 'Jump clears the low laser lane');
assert.ok(Math.abs(camera.position.y - 1.7) < 0.00001, 'Jump lands on floor');
player.controls.dispose();
console.log('Crouch checks passed: C/Ctrl, feet position, headroom, reset, laser body height, jump clearance and landing.');
