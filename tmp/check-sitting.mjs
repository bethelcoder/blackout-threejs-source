import assert from 'node:assert/strict';
import * as THREE from 'three';
import { PlayerControls } from '../src/systems/playerControls.js';
globalThis.document = { addEventListener() {}, removeEventListener() {} };
const camera = new THREE.PerspectiveCamera();
const controls = new PlayerControls(camera, { ownerDocument: document });
controls.controls.isLocked = true;
controls.cameraMode = 'third';
camera.position.set(0.4, 1.7, -3.9);
const original = camera.position.clone();
const position = new THREE.Vector3(0.4, 1.32, -4.88);
const target = new THREE.Vector3(0.4, 1.3, -6);
let stood = 0;
assert.ok(controls.sit(position, target, () => stood++));
assert.equal(controls.isSeated, true);
assert.equal(controls.cameraMode, 'first');
assert.equal(camera.userData.playerHeight, 1.32);
const key = code => controls._onKey({ code, repeat: false, preventDefault() {} }, true);
for (const code of ['KeyW', 'KeyC', 'KeyV']) key(code);
controls.update(0.5);
assert.deepEqual(camera.position.toArray(), position.toArray(), 'Walking/gravity/crouch do not move seated player');
assert.equal(controls.cameraMode, 'first');
assert.equal(controls.sit(position, target), false, 'Already seated cannot sit again');
key('Space');
assert.equal(controls.isSeated, false);
assert.equal(controls.cameraMode, 'third');
assert.deepEqual(camera.position.toArray(), original.toArray());
assert.equal(stood, 1);
assert.equal(controls.jumpQueued, false, 'Standing key does not queue jump');
assert.ok(controls.sit(position, target));
controls.colliders = [new THREE.Box3(new THREE.Vector3(0, 0, -4.3), new THREE.Vector3(0.8, 2, -3.5))];
assert.ok(controls.stand(), 'Blocked original position uses a clear alternative');
assert.ok(!controls._collides(camera.position));
assert.ok(controls.sit(position, target));
controls.teleport(new THREE.Vector3(0, 1.7, 6));
assert.equal(controls.isSeated, false, 'Alarm/teleport clears seated state');
assert.equal(controls.cameraMode, 'third');
assert.equal(camera.userData.playerHeight, 1.7);
controls.grounded = false;
assert.equal(controls.sit(position, target), false, 'Cannot sit in mid-jump');
controls.controls.dispose();
console.log('Sitting checks passed: seat view, movement lock, stand key, camera restore, clear exits, teleport reset and grounded entry.');
