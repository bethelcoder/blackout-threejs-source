import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { arrangeTerminalStation, buildTerminalStation } from '../src/scenes/terminalStation.js';
import { buildLevel2 } from '../src/scenes/level2.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const ctx = new Proxy({}, { get: (_, key) => key.startsWith('create') ? () => ({ addColorStop() {} }) : () => {} });
globalThis.document = { createElement: () => ({ getContext: () => ctx }), createElementNS: () => ({ addEventListener() {}, removeEventListener() {}, set src(value) {} }) };
async function parse(name) {
  const file = fs.readFileSync(`src/assets/models/${name}.glb`);
  return new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), '');
}
const [desk, computer] = await Promise.all([parse('terminal-desk'), parse('retro-computer')]);
const station = arrangeTerminalStation(desk.scene.clone(true), computer.scene.clone(true), { onInteract() {}, getLabel: () => 'Use grid terminal' });
const tableBounds = new THREE.Box3().setFromObject(station.group.children[0]);
const computerBounds = new THREE.Box3().setFromObject(station.computer);
assert.ok(Math.abs(tableBounds.min.y) < 0.00001, 'Desk stands on floor');
assert.ok(Math.abs(computerBounds.min.y - 208.74721 * 0.005) < 0.00001, 'Computer rests on desktop');
assert.ok(computerBounds.min.x > -1.17421 && computerBounds.max.x < -0.39141, 'Computer fits rotated side wing');
assert.ok(computerBounds.min.z > -6.48281 && computerBounds.max.z < -4.91719);
assert.equal(station.computer.children[0].children.length, 2, 'Both original computer parts retained');
let deskTriangles = 0;
station.group.children[0].traverse(object => { if (object.isMesh) deskTriangles += (object.geometry.index?.count ?? object.geometry.attributes.position.count) / 3; });
assert.equal(deskTriangles, 1314, 'Complete desk and all its attached contents retained');
station.group.traverse(object => { if (object.isMesh) assert.ok(object.material.map && object.material.normalMap && object.material.metalnessMap); });
const approach = new THREE.Vector3(0.3, 1.4, -5.2);
const aim = new THREE.Raycaster(approach, new THREE.Vector3(-0.7828, 1.4, -5.7).sub(approach).normalize(), 0, 3.2);
assert.ok(aim.intersectObject(station.computer, true).length > 0, 'Right-facing computer remains reachable');
const seatedEye = new THREE.Vector3(0.4, 1.32, -4.88);
const seatedAim = new THREE.Raycaster(seatedEye, computerBounds.getCenter(new THREE.Vector3()).sub(seatedEye).normalize(), 0, 3.2);
const seatedHit = seatedAim.intersectObject(station.group, true)[0];
let seatedTarget = seatedHit?.object;
while (seatedTarget && seatedTarget !== station.computer) seatedTarget = seatedTarget.parent;
assert.equal(seatedTarget, station.computer, 'Computer can be targeted from chair without desk blocking it');
assert.ok(!station.colliders.some(box => box.containsPoint(new THREE.Vector3(0.3, 0.5, -5.3))), 'Inner corner of L remains open');

const originalLoad = GLTFLoader.prototype.loadAsync;
GLTFLoader.prototype.loadAsync = async url => {
  if (url.includes('terminal-desk')) return { scene: desk.scene.clone(true) };
  if (url.includes('retro-computer')) return { scene: computer.scene.clone(true) };
  return new Promise(() => {});
};
let opens = 0;
const scene = new THREE.Scene();
const level = buildLevel2({ scene, aiState: { raise() {}, decay() {} }, hud: { setObjective() {}, markLevelComplete() {} }, terminalUI: { show() { opens++; }, open: false } });
for (let i = 0; i < 10; i++) await Promise.resolve();
const terminal = scene.getObjectByName('Retro computer grid terminal');
assert.ok(terminal, 'Imported station loads into Level 2');
terminal.userData.onInteract();
assert.equal(opens, 0, 'Laser interlock applies to retro computer');
scene.getObjectByName('Laser shutdown button').userData.onInteract();
terminal.userData.onInteract();
assert.equal(opens, 1, 'Retro computer opens terminal after shutdown');
assert.ok(scene.children.some(object => object.userData.label === 'Use grid terminal' && !object.visible), 'Original screen removed from view');
level.dispose();
assert.equal(scene.getObjectByName('Imported terminal workstation'), undefined);
const lateScene = new THREE.Scene();
const late = buildTerminalStation({ scene: lateScene, colliders: [], onInteract() {}, getLabel() {} });
late.dispose();
await late.ready;
assert.equal(lateScene.children.length, 0, 'Late loads cannot re-add disposed workstation');
GLTFLoader.prototype.loadAsync = originalLoad;
console.log('Workstation checks passed: complete models/textures, clear desktop fit, floor height, reach, L-shaped collision, laser gate, terminal access and cleanup.');
