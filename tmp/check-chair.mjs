import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { arrangeOfficeChair, buildOfficeChair } from '../src/scenes/officeChair.js';
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1024, height: 1024, close() {} });
const file = fs.readFileSync('src/assets/models/office-chair.glb');
const gltf = await new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), '');
const chair = arrangeOfficeChair(gltf.scene.clone(true));
assert.ok(Math.abs(chair.collider.min.y) < 0.00001, 'Wheels rest on floor');
assert.ok(Math.abs(chair.collider.max.y - 1.25) < 0.00001, 'Chair scaled to room');
const facing = new THREE.Vector3(1, 0, 0).applyQuaternion(chair.group.children[0].quaternion);
assert.ok(facing.z < -0.99, 'Seat faces desk');
assert.ok(chair.collider.min.z > -5.7, 'Chair clears front of desk');
assert.ok(chair.collider.min.x > -0.39141, 'Chair clears side wing and retro computer');
assert.ok(chair.collider.max.z < -4.3, 'Chair stays clear of laser approach');
let meshes = 0;
chair.group.traverse(object => { if (object.isMesh) meshes++; });
assert.equal(meshes, 35, 'All original chair meshes retained');
const original = GLTFLoader.prototype.loadAsync;
GLTFLoader.prototype.loadAsync = async () => ({ scene: gltf.scene.clone(true) });
const scene = new THREE.Scene();
const colliders = [];
let seatRequest = null;
const loaded = buildOfficeChair({ scene, colliders, onSit: request => { seatRequest = request; return true; } });
await loaded.ready;
assert.equal(colliders.length, 1);
assert.equal(scene.children.length, 1);
assert.equal(scene.children[0].userData.label, 'Sit at desk');
scene.children[0].userData.onInteract();
assert.ok(seatRequest && seatRequest.position.y > chair.collider.max.y, 'Chair interaction requests seated eye view above backrest');
loaded.dispose();
assert.equal(scene.children.length, 0);
assert.equal(colliders.length, 0);
const cancelled = buildOfficeChair({ scene, colliders });
cancelled.dispose();
await cancelled.ready;
assert.equal(scene.children.length, 0);
GLTFLoader.prototype.loadAsync = original;
console.log('Chair checks passed: complete model, floor height, orientation, desk/computer clearance, collision, cleanup and cancellation.');
